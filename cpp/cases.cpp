int main (){

    int day;
    cout << "enter day number" << endl;
    cin >> day ;

    switch (day)
    {
    case 1:
        cout<<"Monday";
        break;
        
    case 2:
        cout<<"Monday";
        break;
        
    case 3:
        cout<<"Tuesday";
        break;
        
    case 4:
        cout<<"Wednesday";
        break;
        
    case 5:
        cout<<"Thursday";
        break;
        
    case 6:
        cout<<"Friday";
        break;
        
    case 7:
        cout<<"Saturday";
        break;
    
    default:
        cout<<"invalid";
        break;
    }
    



    return 0;

}